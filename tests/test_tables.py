import copy
from dataclasses import replace
from decimal import Decimal
from pathlib import Path
import tempfile
import unittest
from unittest.mock import MagicMock, patch
from uuid import UUID

from lxml import html, etree
from sec_pipeline.tables import (extract_tables, layout_grid, FactScope, load_tables,
                                 select_statements, TableExtractionError)

ROOT = Path(__file__).resolve().parents[1]
HTML = ROOT / 'data/raw/sec/0001193125-26-191507/msft-20260331.htm'
XML = HTML.with_name('msft-20260331_htm.xml')
SCOPE = dict(filing_id=UUID(int=1), html_document_id=UUID(int=2), xml_document_id=UUID(int=3))


class TableTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tables = extract_tables(HTML, XML, **SCOPE)

    def test_complete_inventory_and_stability(self):
        self.assertEqual([t.table_key for t in self.tables],
                         ['income_statement', 'balance_sheet', 'cash_flow'])
        expected = [(76, 76), (66, 76), (132, 131)]
        for table, (cells, facts) in zip(self.tables, expected):
            self.assertEqual(table.structure['inventory']['resolved'], cells)
            self.assertEqual(table.structure['inventory'].get('unresolved', 0), 0)
            refs = {f['xml_id'] for row in table.structure['rows'] for c in row for f in c['fact_references']}
            self.assertEqual(len(refs), facts)
        self.assertEqual(self.tables, extract_tables(HTML, XML, **SCOPE))

    def test_source_locators_resolve_and_preserve_spans(self):
        tree = html.parse(str(HTML))
        for table in self.tables:
            self.assertEqual(len(tree.xpath(table.structure['source_xpath'])), 1)
            for row in table.structure['rows']:
                for cell in row:
                    source = tree.xpath(cell['source_xpath'])
                    self.assertEqual(len(source), 1)
                    self.assertEqual(cell['colspan'], int(source[0].get('colspan', '1')))
                    self.assertEqual(cell['rowspan'], int(source[0].get('rowspan', '1')))

    def test_independent_reference_values_three_per_statement(self):
        # Expectations transcribed from the source, not generated by extractor.
        references = [
            ('income_statement', 'Total revenue', '2026-01-01', '82886000000'),
            ('income_statement', 'Operating income', '2026-01-01', '38398000000'),
            ('income_statement', 'Net income', '2026-01-01', '31778000000'),
            ('balance_sheet', 'Cash and cash equivalents', '2026-03-31', '32105000000'),
            ('balance_sheet', 'Short-term investments', '2026-03-31', '46167000000'),
            ('balance_sheet', 'Total cash, cash equivalents, and short-term investments', '2026-03-31', '78272000000'),
            ('cash_flow', 'Net cash from operations', '2026-01-01', '46679000000'),
            ('cash_flow', 'Net cash used in financing', '2026-01-01', '-11351000000'),
            ('cash_flow', 'Net cash used in investing', '2026-01-01', '-27405000000'),
        ]
        by_key = {t.table_key: t for t in self.tables}
        for kind, label, start, value in references:
            refs = [f for row in by_key[kind].structure['rows'] for c in row
                    if c['row_heading'] == label for f in c['fact_references']
                    if f['period'].get('startDate', f['period'].get('instant')) == start]
            self.assertEqual(len(refs), 1, (kind, label))
            self.assertEqual(Decimal(refs[0]['raw_value']), Decimal(value))

    def test_millions_and_eps_are_separate(self):
        refs = [f for row in self.tables[0].structure['rows'] for c in row for f in c['fact_references']]
        eps = next(f for f in refs if f['concept'].endswith('}EarningsPerShareBasic'))
        self.assertEqual(eps['scale'], '0')
        self.assertEqual(eps['raw_value'], '4.28')
        self.assertTrue(eps['unit']['denominator'][0].endswith('}shares'))
        revenue = next(f for f in refs if f['raw_value'] == '82886000000')
        self.assertEqual(revenue['scale'], '6')
        self.assertEqual(revenue['period'], {'startDate': '2026-01-01', 'endDate': '2026-03-31'})

    def test_display_cash_outflow_does_not_change_xml_sign(self):
        table = self.tables[2]
        row = next(row for row in table.structure['rows'] if row[0]['display_text'] == 'Common stock repurchased')
        ref = next(f for c in row for f in c['fact_references'])
        self.assertEqual(ref['raw_value'], '4627000000')
        self.assertIn('(', '\t'.join(c['display_text'] for c in row))
        self.assertIn(')', '\t'.join(c['display_text'] for c in row))

    def test_numeric_label_facts_are_preserved(self):
        cells = [c for row in self.tables[1].structure['rows'] for c in row if c['classification'] == 'resolved_label']
        self.assertEqual(len(cells), 3)
        self.assertEqual(sum(len(c['fact_references']) for c in cells), 10)

    def test_untagged_cash_has_semantic_repeat_evidence(self):
        cell = next(c for row in self.tables[2].structure['rows'] for c in row if c['cell_id'] == 'r059c003')
        ref = cell['fact_references'][0]
        self.assertEqual(ref['method'], 'same_row_semantic_repeat')
        self.assertEqual(ref['period'], {'instant': '2026-03-31'})
        self.assertEqual(ref['raw_value'], '32105000000')
        self.assertEqual(cell['column_period'], {'startDate': '2026-01-01', 'endDate': '2026-03-31'})

    def test_merged_cell_and_blank_grid(self):
        tree = etree.ElementTree(html.fromstring('<table><tr><td rowspan="2">A</td><td colspan="2">B</td></tr><tr><td></td><td>—</td></tr></table>'))
        rows, grid = layout_grid(tree.getroot(), tree)
        self.assertEqual(grid, [['r000c000', 'r000c001', 'r000c001'], ['r000c000', 'r001c001', 'r001c002']])
        self.assertEqual(rows[1][0]['display_text'], '')
        self.assertEqual(rows[1][1]['display_text'], '—')

    def test_selection_ignores_inserted_layout_table(self):
        tree = html.parse(str(HTML))
        original = select_statements(tree)
        tree.getroot().find('body').insert(0, html.fromstring('<table><tr><td>Net income 31,778</td></tr></table>'))
        self.assertEqual(original, select_statements(tree))

    def test_ambiguous_statement_fails(self):
        tree = html.parse(str(HTML))
        table = select_statements(tree)['income_statement']
        parent = table.getparent()
        parent.append(html.fromstring('<p>INCOME STATEMENTS</p>'))
        parent.append(copy.deepcopy(table))
        with self.assertRaises(TableExtractionError):
            select_statements(tree)

    def changed_html(self, change):
        tree = html.parse(str(HTML))
        change(tree)
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'changed.htm'
            path.write_bytes(html.tostring(tree))
            return extract_tables(path, XML, **SCOPE)

    def test_missing_inline_id_is_unresolved(self):
        def change(tree):
            e = next(e for e in select_statements(tree)['income_statement'].iter() if str(e.tag) == 'ix:nonfraction')
            e.attrib.pop('id')
        tables = self.changed_html(change)
        self.assertEqual(tables[0].structure['inventory'].get('unresolved'), 1)

    def test_wrong_context_or_unit_is_unresolved(self):
        for key in ['contextref', 'unitref', 'name']:
            def change(tree):
                e = next(e for e in select_statements(tree)['income_statement'].iter() if str(e.tag) == 'ix:nonfraction')
                e.set(key, 'us-gaap:Wrong' if key == 'name' else 'wrong')
            tables = self.changed_html(change)
            self.assertEqual(tables[0].structure['inventory'].get('unresolved'), 1)

    def test_duplicate_inline_id_is_unresolved(self):
        def change(tree):
            elements = [e for e in select_statements(tree)['income_statement'].iter()
                        if str(e.tag) == 'ix:nonfraction']
            elements[1].set('id', elements[0].get('id'))
        tables = self.changed_html(change)
        self.assertEqual(tables[0].structure['inventory'].get('unresolved'), 2)

    def test_period_mismatch_is_unresolved(self):
        def change(tree):
            table = select_statements(tree)['income_statement']
            # Change visible year without altering fact evidence.
            for e in table.iter():
                if e.text == '2026':
                    e.text = '2024'
                    break
        tables = self.changed_html(change)
        self.assertGreater(tables[0].structure['inventory'].get('unresolved', 0), 0)

    def test_repeated_amounts_keep_occurrences(self):
        refs = [f for row in self.tables[2].structure['rows'] for c in row for f in c['fact_references'] if f['raw_value'] == '0']
        self.assertGreater(len(refs), 1)
        self.assertGreater(len({f['xml_id'] for f in refs}), 1)

    def test_same_source_ids_rejected(self):
        with self.assertRaises(TableExtractionError):
            extract_tables(HTML, XML, **{**SCOPE, 'html_document_id': UUID(int=3)})

    def test_loader_invalid_scope_and_missing_id_write_nothing(self):
        conn = MagicMock(autocommit=False)
        for scope in [FactScope(UUID(int=7), UUID(int=3), 'facts-v1', {}),
                      FactScope(UUID(int=1), UUID(int=3), 'old-version', {}),
                      FactScope(UUID(int=1), UUID(int=3), 'facts-v1', {})]:
            with self.assertRaises(TableExtractionError):
                load_tables(conn, self.tables, scope)
        conn.execute.assert_not_called()

    def test_loader_rejects_wrong_actual_database_fact(self):
        conn = MagicMock(autocommit=False)
        conn.execute.return_value.fetchone.return_value = None
        ref = next(f for row in self.tables[0].structure['rows'] for c in row for f in c['fact_references'])
        scope = FactScope(UUID(int=1), UUID(int=3), 'facts-v1', {ref['xml_id']: UUID(int=99)})
        with patch('sec_pipeline.tables.store_financial_table') as store:
            with self.assertRaises(TableExtractionError):
                load_tables(conn, self.tables, scope)
            store.assert_not_called()


if __name__ == '__main__':
    unittest.main()
